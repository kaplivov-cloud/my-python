import random  # Подключаем библиотеку random, чтобы компьютер умел выбирать случайные символы

print("--- Генератор надежных паролей ---")
user_input = input("Введи слово или фразу для основы пароля: ")
# Мы спрашиваем у пользователя текст и сохраняем его в переменную user_input. 
# Например, он ввел: "Мой кот!"

clean_chars = []  # Создаем пустой список (коробку), куда будем складывать "хорошие" символы

# --- ШАГ 1: ОЧИСТКА ПОЛЬЗОВАТЕЛЬСКОГО ВВОДА ---
for char in user_input:  # Цикл берет слово пользователя и по одной букве кладет в переменную char
    if char.isalnum():   # Метод isalnum() проверяет: это буква или цифра? 
                         # (Пробел, запятая, восклицательный знак вернут False)
        clean_chars.append(char)  # Если это буква/цифра, кладем её в наш список clean_chars

# --- ШАГ 2: ДОБАВЛЕНИЕ СВОИХ СИМВОЛОВ ДЛЯ НАДЕЖНОСТИ ---
# Если мы будем брать символы только из слова "кот", пароль будет слабым. 
# Поэтому мы создаем строку со всеми английскими буквами, цифрами и спецсимволами.
extra_chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*"

for char in extra_chars:  # Проходимся по каждому символу из этой огромной строки
    clean_chars.append(char)  # И тоже добавляем его в наш общий список clean_chars

print(f"Символов в базе: {len(clean_chars)}") 
# Выводим, сколько всего символов у нас накопилось. Если пользователь ввел "кот", 
# то к его 3 буквам добавятся еще 72 символа из extra_chars. Итого будет 75.

# --- ШАГ 3: ГЕНЕРАЦИЯ ПАРОЛЯ ---
password = ""  # Создаем пустую строку, куда будем "склеивать" наш пароль

for _ in range(8):  # Цикл повторяется ровно 8 раз (нам нужен пароль из 8 символов).
                    # Знак _ (нижнее подчеркивание) значит, что переменная цикла нам не важна.
    random_char = random.choice(clean_chars)  # random.choice берет ОДИН случайный элемент из списка clean_chars
    password += random_char  # Приклеиваем этот случайный символ в конец строки password

print(f"Твой пароль: {password}")  # Показываем готовый пароль

# --- ШАГ 4: ПРОВЕРКА НАДЕЖНОСТИ (УСЛОЖНЕНИЕ) ---
# Мы создаем три "флажка". Изначально мы предполагаем, что в пароле ничего нет (False)
has_letter = False   # Есть ли буква?
has_digit = False    # Есть ли цифра?
has_special = False  # Есть ли спецсимвол?

for char in password:  # Берем наш готовый пароль и снова разбираем его по буквам
    if char.isalpha():     # Если текущий символ — это буква (английская)
        has_letter = True  # Поднимаем флажок "Есть буква!"
    elif char.isdigit():   # Если это цифра
        has_digit = True   # Поднимаем флажок "Есть цифра!"
    else:                  # Если это не буква и не цифра (значит, это ! @ # $ и т.д.)
        has_special = True # Поднимаем флажок "Есть спецсимвол!"

print("Надежность пароля:")
# Теперь смотрим, какие флажки подняты. 
# Если все три True (и буква, и цифра, и спецсимвол) — пароль идеален.
if has_letter and has_digit and has_special:
    print("🔥 ОТЛИЧНО! Пароль надежный.")
# Если есть буквы и цифры, но нет спецсимволов — нормально, но можно лучше.
elif has_letter and has_digit:
    print("👍 Нормально, но можно добавить спецсимволы.")
# Во всех остальных случаях (например, только буквы) — пароль слабый.
else:
    print("⚠️ Слабый пароль.")